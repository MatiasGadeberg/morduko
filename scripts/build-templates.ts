import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { PNG } from "pngjs";
import { rgbaToGray } from "../src/scan/image.ts";
import { NORMAL_SIDE, normalizeGray } from "../src/scan/normalize.ts";

const dir = "/tmp/morduko-digits";
const files = readdirSync(dir)
  .filter((file) => file.endsWith(".png"))
  .sort();

function pack(bits: Uint8Array): string {
  const bytes = new Uint8Array(Math.ceil(bits.length / 8));
  for (let i = 0; i < bits.length; i++) {
    if (bits[i]) bytes[i >> 3] |= 1 << (i & 7);
  }
  return Buffer.from(bytes).toString("base64");
}

const items: { digit: number; font: string; bits: string }[] = [];
const failed: string[] = [];
for (const file of files) {
  const stem = file.replace(/\.png$/, "");
  const split = stem.lastIndexOf("__");
  const font = stem.slice(0, split);
  const digit = Number(stem.slice(split + 2));
  const png = PNG.sync.read(readFileSync(`${dir}/${file}`));
  const gray = rgbaToGray(png.data, png.width, png.height);
  const bitmap = normalizeGray(gray);
  if (!bitmap || bitmap.length !== NORMAL_SIDE * NORMAL_SIDE) {
    failed.push(file);
    continue;
  }
  items.push({ digit, font, bits: pack(bitmap) });
}

if (failed.length) {
  console.error("failed to normalize", failed.join(", "));
  process.exit(1);
}

const body = items
  .map((item) => `  { digit: ${item.digit}, font: ${JSON.stringify(item.font)}, bits: ${JSON.stringify(item.bits)} },`)
  .join("\n");

const source = `// Generated by scripts/build-templates.ts. Do not edit by hand.
export const TEMPLATE_SIDE = ${NORMAL_SIDE};

export type DigitTemplate = {
  digit: number;
  font: string;
  bits: string;
};

export const TEMPLATES: DigitTemplate[] = [
${body}
];
`;

writeFileSync(new URL("../src/scan/templates.ts", import.meta.url), source);
console.log(`wrote ${items.length} templates`);
